function leafKeys(obj, prefix = '') {
  const keys = [];
  if (typeof obj === 'string') return [prefix];
  if (obj && typeof obj === 'object') {
    for (const [k, v] of Object.entries(obj)) keys.push(...leafKeys(v, prefix ? `${prefix}.${k}` : k));
  }
  return keys;
}

const zk = new Set(leafKeys(zh));
